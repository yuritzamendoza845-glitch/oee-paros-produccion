-- =====================================================================================
-- 01_ddl.sql  |  Esquema relacional OEE / paros de producción (PostgreSQL 14+)
-- Ejecutar con un usuario propietario:  psql -d oee -v ON_ERROR_STOP=1 -f 01_ddl.sql
-- Idempotente: usa IF NOT EXISTS donde es posible.
-- =====================================================================================
CREATE EXTENSION IF NOT EXISTS btree_gist;     -- necesaria para la restricción de no solapamiento

CREATE SCHEMA IF NOT EXISTS oee;     -- modelo analítico (dimensiones + hechos)
CREATE SCHEMA IF NOT EXISTS stg;     -- zona de aterrizaje del ETL
CREATE SCHEMA IF NOT EXISTS etl;     -- control de lotes, rechazos, funciones del pipeline
CREATE SCHEMA IF NOT EXISTS audit;   -- bitácora de cambios

-- ------------------------------------------------------------------ DIMENSIONES / MAESTROS
CREATE TABLE IF NOT EXISTS oee.dim_maquina (
    maquina_id  smallint PRIMARY KEY,
    nombre      text     NOT NULL UNIQUE,
    linea       text     NOT NULL DEFAULT 'Vinilos y témperas',
    activa      boolean  NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS oee.dim_turno (
    turno_id         smallint PRIMARY KEY,                 -- 0 = sin dato
    nombre           text     NOT NULL UNIQUE,
    hora_inicio      time,
    hora_fin         time,
    horas_nominales  numeric(4,1)
);

CREATE TABLE IF NOT EXISTS oee.dim_operario (
    operario_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- 0 = sin dato
    nombre       text    NOT NULL UNIQUE,
    activo       boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS oee.dim_referencia (
    referencia_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 0 = sin dato
    nombre         text    NOT NULL UNIQUE,
    marca          text,
    volumen_cc     smallint,
    num_colores    smallint
);

CREATE TABLE IF NOT EXISTS oee.dim_area_impacto (
    area_id  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS oee.dim_motivo_paro (
    motivo_id      smallint PRIMARY KEY CHECK (motivo_id BETWEEN 1 AND 18),   -- = código del P-MTO-22
    nombre         text     NOT NULL,
    area_id        smallint NOT NULL REFERENCES oee.dim_area_impacto,
    es_planificado boolean  NOT NULL,       -- true: sale del tiempo planificado (no resta Disponibilidad)
    categoria_oee  text     NOT NULL CHECK (categoria_oee IN
        ('AVERIA','AJUSTE','CAMBIO_REFERENCIA','ESPERA','ABASTECIMIENTO','CALIDAD','ORGANIZACIONAL','PLANIFICADO'))
);

CREATE TABLE IF NOT EXISTS oee.dim_subcodigo_paro (
    subcodigo_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    motivo_id     smallint NOT NULL REFERENCES oee.dim_motivo_paro,
    clave         text     NOT NULL,                -- '1.2.C', '5.11' ...
    nombre        text     NOT NULL,
    nivel         smallint NOT NULL,                -- 1 = sistema, 2 = componente
    clave_padre   text,
    UNIQUE (motivo_id, clave)
);

-- Catálogo del campo histórico "Tipo de paro" (horas de turno no trabajadas)
CREATE TABLE IF NOT EXISTS oee.dim_tipo_paro_maquina (
    tipo_paro_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                text    NOT NULL UNIQUE,
    pierde_disponibilidad boolean NOT NULL   -- false = sin demanda/programación (fuera del OEE, entra al TEEP)
);

-- Meta de producción (pacas/hora). referencia_id = 0 => meta por defecto de la máquina.
CREATE TABLE IF NOT EXISTS oee.meta_produccion (
    maquina_id      smallint NOT NULL REFERENCES oee.dim_maquina,
    referencia_id   integer  NOT NULL REFERENCES oee.dim_referencia,
    meta_pacas_hora numeric(8,2) NOT NULL CHECK (meta_pacas_hora > 0),
    origen          text NOT NULL DEFAULT 'ESTIMADA_P90' CHECK (origen IN ('OFICIAL','ESTIMADA_P90')),
    actualizado_en  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (maquina_id, referencia_id)
);

CREATE TABLE IF NOT EXISTS oee.dim_fecha (
    fecha          date PRIMARY KEY,
    anio           smallint NOT NULL,
    trimestre      smallint NOT NULL,
    mes            smallint NOT NULL,
    nombre_mes     text     NOT NULL,
    semana_iso     smallint NOT NULL,
    dia_semana     smallint NOT NULL,           -- 1 = lunes
    es_fin_semana  boolean  NOT NULL
);

-- ------------------------------------------------------------------------- TABLA DE HECHOS
-- Grano: una fila del libro "Base De Datos" (hoja hora-a-hora consolidada por turno/operaria).
-- tipo_registro = COMPLEMENTO_PAROS cuando la fila solo aporta paros adicionales de un turno.
CREATE TABLE IF NOT EXISTS oee.registros_produccion (
    registro_id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    row_hash             char(40)    NOT NULL UNIQUE,            -- llave de idempotencia del ETL
    fecha                date        NOT NULL REFERENCES oee.dim_fecha,
    maquina_id           smallint    NOT NULL REFERENCES oee.dim_maquina,
    turno_id             smallint    NOT NULL DEFAULT 0 REFERENCES oee.dim_turno,
    operario_id          integer     NOT NULL DEFAULT 0 REFERENCES oee.dim_operario,
    referencia_id        integer     NOT NULL DEFAULT 0 REFERENCES oee.dim_referencia,
    tipo_registro        text        NOT NULL CHECK (tipo_registro IN ('PRODUCCION','COMPLEMENTO_PAROS')),
    pacas_producidas     numeric(10,2) CHECK (pacas_producidas >= 0),
    pacas_no_conformes   numeric(10,2) NOT NULL DEFAULT 0 CHECK (pacas_no_conformes >= 0),  -- ver nota calidad
    horas_programadas    numeric(5,2)  NOT NULL DEFAULT 0 CHECK (horas_programadas BETWEEN 0 AND 24),
    horas_no_programadas numeric(5,2)  NOT NULL DEFAULT 0 CHECK (horas_no_programadas BETWEEN 0 AND 24),
    tipo_paro_id         integer REFERENCES oee.dim_tipo_paro_maquina,
    observacion          text,
    observacion_paro     text,
    calidad_dato         text NOT NULL DEFAULT 'OK' CHECK (calidad_dato IN ('OK','REVISAR','POSIBLE_DUPLICADO')),
    -- cifras desnormalizadas por el trigger de detalle (consistencia de duraciones)
    paro_planificado_min   numeric(8,2) NOT NULL DEFAULT 0,
    paro_no_planificado_min numeric(8,2) NOT NULL DEFAULT 0,
    archivo_origen       text,
    fila_origen          integer,
    lote_id              bigint,
    creado_en            timestamptz NOT NULL DEFAULT now(),
    actualizado_en       timestamptz NOT NULL DEFAULT now(),
    CHECK (tipo_registro = 'COMPLEMENTO_PAROS' OR horas_programadas > 0 OR pacas_producidas > 0)
);
COMMENT ON COLUMN oee.registros_produccion.pacas_no_conformes IS
 'El libro de origen NO registra producto no conforme. Por defecto 0 => Calidad = 100%. '
 'Cuando Calidad entregue el dato (o se integre el HMI), se carga aquí y el OEE se ajusta solo.';

CREATE INDEX IF NOT EXISTS ix_reg_fecha_maq    ON oee.registros_produccion (fecha, maquina_id);
CREATE INDEX IF NOT EXISTS ix_reg_maq_ref      ON oee.registros_produccion (maquina_id, referencia_id);
CREATE INDEX IF NOT EXISTS ix_reg_operario     ON oee.registros_produccion (operario_id);
CREATE INDEX IF NOT EXISTS ix_reg_calidad      ON oee.registros_produccion (calidad_dato) WHERE calidad_dato <> 'OK';
CREATE INDEX IF NOT EXISTS ix_reg_fecha_brin   ON oee.registros_produccion USING brin (fecha);

-- Detalle granular: una fila por (registro, código de paro).
CREATE TABLE IF NOT EXISTS oee.detalle_paros_produccion (
    detalle_id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    registro_id          bigint   NOT NULL REFERENCES oee.registros_produccion ON DELETE CASCADE,
    maquina_id           smallint NOT NULL REFERENCES oee.dim_maquina,   -- lo completa el trigger
    motivo_id            smallint NOT NULL REFERENCES oee.dim_motivo_paro,
    subcodigo_id         integer  REFERENCES oee.dim_subcodigo_paro,
    minutos              numeric(8,2) NOT NULL CHECK (minutos > 0),
    area_involucrada     text CHECK (area_involucrada IN ('Operarios','Personal_de_mantenimiento')),
    personal_involucrado text,
    -- Opcionales: solo cuando existe marca de tiempo (HMI / formato hora-a-hora digitalizado)
    inicio               timestamptz,
    fin                  timestamptz,
    creado_en            timestamptz NOT NULL DEFAULT now(),
    CHECK ((inicio IS NULL) = (fin IS NULL)),
    CHECK (fin IS NULL OR fin > inicio),
    -- Regla: en una misma máquina no pueden solaparse dos paros con marca de tiempo
    EXCLUDE USING gist (maquina_id WITH =, tstzrange(inicio, fin, '[)') WITH &&) WHERE (inicio IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_det_registro ON oee.detalle_paros_produccion (registro_id);
CREATE INDEX IF NOT EXISTS ix_det_motivo   ON oee.detalle_paros_produccion (motivo_id, subcodigo_id);

-- ---------------------------------------------------------------------------- STAGING (ETL)
CREATE TABLE IF NOT EXISTS etl.lotes (
    lote_id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    archivo          text NOT NULL,
    sha256           char(64),
    iniciado_en      timestamptz NOT NULL DEFAULT now(),
    finalizado_en    timestamptz,
    estado           text NOT NULL DEFAULT 'EN_CURSO' CHECK (estado IN ('EN_CURSO','OK','ERROR')),
    filas_leidas     integer,
    filas_insertadas integer,
    filas_actualizadas integer,
    filas_eliminadas integer,
    mensaje          text
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_lotes_sha_ok ON etl.lotes (sha256) WHERE estado = 'OK';

CREATE TABLE IF NOT EXISTS etl.rechazos (
    rechazo_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    lote_id      bigint REFERENCES etl.lotes ON DELETE CASCADE,
    fila_origen  integer,
    regla        text NOT NULL,
    severidad    text NOT NULL CHECK (severidad IN ('ERROR','WARNING')),
    detalle      text,
    creado_en    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stg.registros (
    lote_id bigint NOT NULL, row_hash char(40) NOT NULL, fila_origen integer, archivo_origen text,
    fecha date, maquina text, turno text, operario text, referencia text,
    pacas numeric, horas_programadas numeric, horas_no_programadas numeric,
    tipo_paro_maquina text, pierde_disp_tpm boolean, observacion text, observacion_paro text,
    tipo_registro text, calidad_dato text,
    PRIMARY KEY (lote_id, row_hash)
);
CREATE TABLE IF NOT EXISTS stg.paros (
    lote_id bigint NOT NULL, row_hash char(40) NOT NULL, motivo_id smallint, minutos numeric,
    subcodigo text, area_involucrada text, personal_involucrado text
);
CREATE INDEX IF NOT EXISTS ix_stg_paros ON stg.paros (lote_id, row_hash);

-- ------------------------------------------------------------------------------ AUDITORÍA
CREATE TABLE IF NOT EXISTS audit.log_cambios (
    log_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tabla      text        NOT NULL,
    pk         text        NOT NULL,
    operacion  text        NOT NULL CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
    usuario    text        NOT NULL DEFAULT current_user,
    en         timestamptz NOT NULL DEFAULT now(),
    antes      jsonb,
    despues    jsonb
);
CREATE INDEX IF NOT EXISTS ix_audit_tabla_pk ON audit.log_cambios (tabla, pk, en DESC);
